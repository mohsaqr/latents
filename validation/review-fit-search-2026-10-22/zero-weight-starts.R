suppressPackageStartupMessages(pkgload::load_all(quiet = TRUE))
quiet <- function(expr) withCallingHandlers(expr, warning=function(w){cat('WARNING:',class(w)[1],conditionMessage(w),'\n');invokeRestart('muffleWarning')},message=function(m)invokeRestart('muffleMessage'))
set.seed(803)
d <- data.frame(y=c(rnorm(50,-3,.5),rnorm(50,3,.5)),w=1)
base <- quiet(lpa(d,'y',2,weights='w',n_starts=10,seed=1))
plain <- rbind(d,data.frame(y=0,w=0))
extreme <- rbind(d,data.frame(y=1e4,w=0))
show <- function(label,f) {
 cat('\n',label,'LL',format(f$log_likelihood,digits=16),'converged',f$converged,'\n')
 cat('means',format(f$means,digits=16),'variances',format(f$variances,digits=16),'effective_counts',colSums(f$subject_posteriors),'\n')
 print(get_results(f,'starts'))
}
a <- quiet(lpa(plain,'y',2,weights='w',n_starts=10,seed=1)); show('ZERO y=0, kmeans10',a)
b <- quiet(lpa(extreme,'y',2,weights='w',n_starts=10,seed=1));show('ZERO y=10000, kmeans10',b)
c <- quiet(lpa(extreme,'y',2,weights='w',n_starts=100,seed=1));show('ZERO y=10000, kmeans100',c)
good <- quiet(lpa(extreme,'y',2,weights='w',n_starts=1,seed=1,start=starting_values(base)));show('ZERO y=10000, supplied good start',good)
emem <- quiet(lpa(extreme,'y',2,weights='w',n_starts=10,seed=1,search='emEM'));show('ZERO y=10000, emEM10',emem)
cat('\nSame-N LL deficit',a$log_likelihood-b$log_likelihood,'base rescaled',base$log_likelihood*101/100,'\n')
stopifnot(abs(a$log_likelihood-good$log_likelihood)<1e-8,b$log_likelihood<a$log_likelihood-100)
saveRDS(list(data=extreme,base=base,zero_at_zero=a,zero_extreme=b,zero_extreme100=c,good=good,emem=emem),'validation/review-fit-search-2026-10-22/zero-weight-starts.rds')
