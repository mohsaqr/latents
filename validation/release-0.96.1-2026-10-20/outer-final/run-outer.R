arguments <- commandArgs(trailingOnly = TRUE)
stopifnot(length(arguments) == 1L, dir.exists(arguments[[1L]]))
output <- arguments[[1L]]
Sys.setenv(NOT_CRAN = "true")
production <- sort(list.files("R", pattern = "[.]R$", full.names = TRUE))
before <- tools::md5sum(production)
utils::write.csv(data.frame(path = names(before), md5 = unname(before)),
                 file.path(output, "production-before.csv"), row.names = FALSE)
cat("Package version:", read.dcf("DESCRIPTION", fields = "Version"), "\n")
cat("Installed worker package:", normalizePath(find.package("latents")), "\n")
stopifnot(normalizePath(find.package("latents")) ==
            normalizePath(file.path(output, "rlib", "latents")))
cat("Scratch:", normalizePath("."), "\n")
cat("Started:", format(Sys.time(), tz = "UTC"), "UTC\n")
started <- proc.time()
pkgload::load_all(".", quiet = TRUE)
results <- testthat::test_dir("equivalence", load_package = "none",
                              reporter = "summary", stop_on_failure = FALSE)
saveRDS(results, file.path(output, "results.rds"))
cases <- as.data.frame(results)
saveRDS(cases, file.path(output, "cases.rds"))
utils::write.csv(cases[setdiff(names(cases), "result")],
                 file.path(output, "cases.csv"), row.names = FALSE)
cat("\nFINAL TOTALS\n")
print(colSums(cases[c("nb", "failed", "skipped", "error", "warning", "passed")]))
cat("Cases:", nrow(cases), "\n")
cat("Elapsed seconds:", (proc.time() - started)[["elapsed"]], "\n")
unchanged <- identical(before, tools::md5sum(production))
cat("Scratch production source unchanged:", unchanged, "\n")
cat("Completed:", format(Sys.time(), tz = "UTC"), "UTC\n")
print(utils::sessionInfo())
quit(status = as.integer(any(cases$failed > 0 | cases$error) || !unchanged))
