suppressMessages(devtools::load_all(".", quiet=TRUE))
try_msg <- function(expr) tryCatch({force(expr); "OK"}, error=function(e) paste0("[", class(e)[1], "] ", conditionMessage(e)))
fit <- multilpa(course_engagement, vars=c("browse","lectures","forum_read","forum_post","attendance"), id="student", n_profiles=2, n_group_classes=2, n_starts=4, seed=1)
cat("get_results(fit):", try_msg(get_results(fit, "nonsense")), "\n\n")
d <- diagnostics(fit, plots=FALSE)
cat("get_results(diag):", try_msg(get_results(d, "nonsense")), "\n\n")
cat("plot(fit):", try_msg(plot(fit, what="nonsense")), "\n\n")
cat("plot_views():\n"); print(plot_views())
cat("\nplot_views(fit):", try_msg(print(plot_views(fit))), "\n")
cat("\ndiagnostics(what=):", try_msg(diagnostics(fit, plots=FALSE, what="residuals")), "\n")
cat("\nreport(sections=):", try_msg(report(fit, plots=FALSE, sections="diagnostics")), "\n")
cat("\nreport(file=):", try_msg(report(fit, plots=FALSE, file="x.html")), "\n")
cat("\nplot(d, what=):", try_msg(plot(d, what="entropy")), "\n")
cat("\nplot_diagnostics(fit,'entropy') class:", class(plot_diagnostics(fit, "entropy")), "\n")
cat("\nplot(fit) default class:", class(plot(fit)), "\n")
cat("\nplot(fit,'all') class:", class(plot(fit, what="all")), "\n")
cat("\ndescriptives(fit) class:", class(descriptives(fit)), "\n")
cat("\nsummary(fit) tables:\n"); print(names(unclass(summary(fit))))
