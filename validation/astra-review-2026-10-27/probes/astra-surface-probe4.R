library(latents, lib.loc='/private/tmp/astra-review/lib')
set.seed(1027)
d <- data.frame(id=rep(1:25,each=4),x=rnorm(100),y=rnorm(100),w=rep(c(rep(1,20),rep(0,5)),each=4))
f <- suppressWarnings(multilpa(d,c('x','y'),id='id',n_profiles=2,n_group_classes=2,family='restricted_cross_level',weights='w',n_starts=2,seed=1))
cat('CROSS LEVEL ZERO WEIGHTS\n');print(f$sampling_weights);print(dim(f$group_posteriors));print(sum(complete.cases(f$group_posteriors)))
print(latents:::.latents_level_classification(f,'groups'))
cat('sum estimated count vs positive groups\n');print(c(estimated=sum(latents:::.latents_level_classification(f,'groups')$estimated_n),positive=sum(f$sampling_weights>0)))
f <- suppressWarnings(lpa(d,c('x','y'),n_profiles=2,n_starts=1,seed=1))
s <- suppressWarnings(sensitivity(f,seeds=1:3,max_iter=0,n_starts=1))
cat('UNCONVERGED SENSITIVITY\n'); print(s);p<-plot(s);print(p$labels$title);print(unique(p$data$status))
