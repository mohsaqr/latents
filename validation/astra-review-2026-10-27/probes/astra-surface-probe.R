options(warn=1)
pkgload::load_all('.', quiet=TRUE)
set.seed(1027)
d <- data.frame(id=rep(1:20,each=5),x=rnorm(100),y=rnorm(100))
f <- lpa(d,c('x','y'),n_profiles=1,n_starts=1,seed=1)
cat('GET_TNA_LPA\n');print(tryCatch(get_tna(f),error=conditionMessage))
cat('BIND_COLLISION\n')
.vars <- d
z <- tryCatch(lpa(.vars, vars=c('x','y'), n_profiles=1,n_starts=1,seed=1),error=identity)
if(inherits(z,'condition')) {print(class(z));print(conditionMessage(z))} else cat('fit LL',z$log_likelihood,'\n')
a <- suppressWarnings(multilpa(d,c('x','y'),id='id',family='additive',n_group_classes=2,n_starts=2,seed=1))
da <- diagnostics(a,plots=FALSE)
cat('ADDITIVE DEFAULT DIAGNOSTICS TABLE\n');print(as.data.frame(da));print(names(get_results(da,'all')))
r <- suppressWarnings(mixture_regression(y~x,d,id='id',n_classes=2,n_group_classes=2,n_starts=2,seed=1))
cat('REGRESSION FIT CLASS AND CLASSIFICATION\n');print(class(r));print(get_results(r,'classification'));print(get_results(diagnostics(r,plots=FALSE),'checks'))
