devtools::load_all(quiet=TRUE)
Sys.setenv(NOT_CRAN='true')
probe <- function(name, expr) {
  cat('\nPROBE:',name,'\n')
  tryCatch(withCallingHandlers({ value <- force(expr); print(value) }, warning=function(w) {cat('WARNING:',class(w)[1],conditionMessage(w),'\n');invokeRestart('muffleWarning')}), error=function(e)cat('ERROR:',class(e)[1],conditionMessage(e),'\n'))
}
set.seed(1310)
d <- data.frame(g=rep(1:20,each=10), x=rnorm(200), z=rnorm(200))
d$x <- d$x + rep(c(-2,2),each=100)
fit <- lpa(d,c('x','z'),2,n_starts=1,seed=1,tol=1e-10)
probe('bars intervals FALSE layers', {p<-plot(fit,what='bars',intervals=FALSE); vapply(p$layers,function(l)class(l$geom)[1],character(1))})
probe('profiles intervals FALSE layers', {p<-plot(fit,what='profiles',intervals=FALSE); vapply(p$layers,function(l)class(l$geom)[1],character(1))})
centered <- multilpa(d,c('x','z'),'g',2,1,centering='grand',n_starts=1,seed=1)
probe('centered all', names(plot(centered,what='all',intervals=FALSE)))
noise <- lpa(d,c('x','z'),2,noise=TRUE,n_starts=1,seed=1)
probe('noise generic entropy',plot(noise,what='entropy'))
probe('noise named entropy',{p<-plot_diagnostics(noise,what='entropy'); c(subtitle=p$labels$subtitle,range=range(p$data$entropy),posterior_sum=range(rowSums(noise$subject_posteriors)))})
probe('noise named AvePP',{p<-plot_diagnostics(noise,what='avepp'); head(p$data)})
weighted_data <- d; weighted_data$w <- c(rep(1,100),rep(10,100))
weighted <- lpa(weighted_data,c('x','z'),2,weights='w',n_starts=1,seed=1,tol=1e-10)
probe('weighted entropy table versus plot', {p<-plot(weighted,what='entropy'); list(table=get_results(weighted,'entropy'), subtitle=p$labels$subtitle)})
b <- data.frame(x=rnorm(160), n=rep(c(10L,20L),80))
b$success <- rbinom(160,b$n,plogis(.5+b$x));b$failure<-b$n-b$success
bin <- mixture_regression(cbind(success,failure)~x,b,1,family='binomial',n_starts=1,seed=1)
probe('binomial training predict identity',{a<-predict(bin); new<-predict(bin,b); head(data.frame(training=a$fitted,newdata=new$fitted,n=b$n,ratio=a$fitted/new$fitted))})
probe('mixture missing data error class',predict(bin,data.frame(x=NA_real_)))
probe('mixture newdata missing predictor error class',predict(bin,data.frame(q=1)))
probe('mixture zero rows', predict(bin,b[FALSE,]))
probe('seed NULL RNG advances', {before<-.Random.seed;simulate(bin,seed=NULL); identical(before,.Random.seed)})
probe('seed integer restores RNG',{before<-.Random.seed;simulate(bin,seed=12);identical(before,.Random.seed)})
probe('docs plot method aliases',{rd<-tools::parse_Rd('man/latents-plots.Rd'); aliases<-vapply(Filter(function(x)identical(attr(x,'Rd_tag'),'\\alias'),rd),paste0,character(1),collapse='');aliases})
probe('legacy enumeration what abbreviations',{grid<-enumerate_lpa(d,c('x','z'),1:2,n_starts=1,seed=1);plot(grid,what='enum')})
probe('weighted tree agrees weighted counts',{
  wg<-enumerate_lpa(weighted_data,c('x','z'),1:2,weights='w',n_starts=1,seed=1)
  wf<-get_candidate(wg,n_profiles=2,model="EEI")
  tree<-plot_tree(wg)
  list(tree=tree$layers[[2]]$data[tree$layers[[2]]$data$n_profiles==2,c('profile','share')],key=latents:::.gg_profile_key(wf)[c('profile','share')])
})
probe('fitted predictor-only posterior ids unnecessary',predict(bin,b[1:2,],type='posterior'))
probe('named plots on inherited subclass', {subfit<-fit; class(subfit)<-c('my_lpa',class(subfit));plot_profiles(subfit)})
set.seed(11)
rgd <- data.frame(id=rep(1:35,each=4),t=rep(0:3,35),y=2+.5*rep(0:3,35)+rep(rnorm(35),each=4)+rnorm(140,.1))
grow <- mixture_regression(y~t,rgd,1,id='id',class_level='group',random=~1,n_starts=1,seed=1,vcov_type='none')
probe('growth seeded simulation rows and RNG',{before<-.Random.seed;a<-simulate(grow,nsim=2,seed=19);list(dim=dim(a),head=head(a),reproducible=identical(a,simulate(grow,2,19)),rng=identical(before,.Random.seed))})
probe('growth named diagnostics',{p<-plot_diagnostics(grow);names(p)})
probe('growth no inference trajectories',{p<-plot(grow,spread=0,max_persons=0);list(class=class(p),layer_types=vapply(p$layers,function(l)class(l$geom)[1],character(1)))})
probe('growth no inference random build', ggplot2::ggplot_build(plot(grow,what='random')) |> class())
probe('ported mixture plot has no draw side effect inside loop', {
  grDevices::pdf('validation/audit-2026-10-13/plots-docs/side-effects.pdf')
  grid::grid.newpage()
  before<-length(grid::grid.ls(print=FALSE)$name)
  invisible(lapply(1:2,function(i)plot(bin)))
  after<-length(grid::grid.ls(print=FALSE)$name)
  print(plot(bin))
  explicit<-length(grid::grid.ls(print=FALSE)$name)
  grDevices::dev.off()
  c(before=before,after_loop=after,after_print=explicit)
})
