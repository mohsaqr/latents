pkgload::load_all(quiet=TRUE)
quiet<-function(x) suppressWarnings(suppressMessages(x))
set.seed(104)
d<-data.frame(g=rep(1:20,each=4),t=rep(1:4,20),y=rnorm(80),z=rnorm(80),w=rep(1:20,each=4))
a<-quiet(lta(d,c("y","z"),"g",time="t",n_profiles=2,transitions="occasion",weights="w",n_starts=1,max_iter=50,seed=1))
b<-quiet(lta(d,c("y","z"),"g",time="t",n_profiles=2,measurement="occasion",weights="w",n_starts=1,max_iter=50,seed=1))
cat("weighted\n"); print(all.equal(.latents_comparison_signature(a),.latents_comparison_signature(b))); weighted<-compare_models(a=a,b=b)
stopifnot(all(weighted$bic_groups==c(a$bic,b$bic)),nrow(get_results(weighted,"classification"))==4)
dc<-transform(d,y=ifelse(y>0,"high","low"),z=ifelse(z>0,"high","low"))
a<-quiet(lta(dc,c("y","z"),"g",time="t",n_profiles=2,categorical=c("y","z"),n_starts=1,max_iter=50,seed=1))
b<-quiet(lta(dc,c("y","z"),"g",time="t",n_profiles=2,categorical=c("y","z"),transitions="occasion",n_starts=1,max_iter=50,seed=1))
cat("categorical\n"); print(all.equal(.latents_comparison_signature(a),.latents_comparison_signature(b))); categorical<-compare_models(a=a,b=b)
stopifnot(all(categorical$bic_groups==c(a$bic,b$bic)),nrow(get_results(categorical,"classification"))==4)
dp<-transform(d,y=rpois(80,3))
a<-quiet(lta(dp,"y","g",time="t",n_profiles=2,count="y",n_starts=1,max_iter=50,seed=1))
b<-quiet(lta(dp,"y","g",time="t",n_profiles=2,count="y",transitions="occasion",n_starts=1,max_iter=50,seed=1))
cat("count\n"); print(all.equal(.latents_comparison_signature(a),.latents_comparison_signature(b))); count<-compare_models(a=a,b=b)
stopifnot(all(count$bic_groups==c(a$bic,b$bic)),nrow(get_results(count,"classification"))==4)
cat("Weighted, all-categorical, and count transition comparisons: passed\n")
