Sys.setenv(OPENBLAS_NUM_THREADS=1,OMP_NUM_THREADS=1,VECLIB_MAXIMUM_THREADS=1)
pkgload::load_all('.',quiet=TRUE)
set.seed(91)
n <- 120L
class <- rep(1:2,each=n/2)
d <- data.frame(y1=rnorm(n,5*class),y2=rnorm(n,4*class),outcome=rnorm(n,3*class,2))
str(d)
f <- lpa(d,c('y1','y2'),2,n_starts=2,seed=3)
r <- as.data.frame(three_step(f,d,'outcome',method='modal',vcov_type='independent'))
assigned <- max.col(f$subject_posteriors,ties.method='first')
means <- tapply(d$outcome,assigned,mean)
variances <- vapply(seq_len(2),function(k){y<-d$outcome[assigned==k];sum((y-mean(y))^2)/length(y)^2*n/(n-1)},numeric(1))
expected <- data.frame(estimate=unname(means),standard_error=sqrt(variances))
print(r)
cat('max mean error',max(abs(r$estimate-expected$estimate)),'max SE error',max(abs(r$standard_error-expected$standard_error)),'\n')
stopifnot(max(abs(r$estimate-expected$estimate))<1e-12,max(abs(r$standard_error-expected$standard_error))<1e-12)
p <- as.data.frame(three_step(f,d,'outcome',method='modal',vcov_type='independent',contrast='pairs'))
print(p)
stopifnot(abs(p$standard_error-sqrt(sum(variances)))<1e-12)
