library(testthat)
base <- "validation/release-audit-2026-10-28/release"
initial <- as.data.frame(readRDS(file.path(base, "unit-results.rds")))
rerun <- as.data.frame(readRDS(file.path(base, "parallel-results.rds")))
rerun <- rbind(rerun, as.data.frame(readRDS(file.path(base, "search-results.rds"))))
rerun <- rbind(rerun, as.data.frame(readRDS(file.path(base, "refusals-results.rds"))))
stopifnot(all(unique(rerun$file) %in% unique(initial$file)))
combined <- rbind(initial[!initial$file %in% unique(rerun$file), ], rerun)
stopifnot(setequal(unique(combined$file), unique(initial$file)))
counts <- c("nb", "failed", "skipped", "error", "warning", "passed")
cat("Initial sandbox full run:\n")
print(colSums(initial[counts]))
cat("Nine-file rerun with socket/CPU-count access:\n")
print(colSums(rerun[counts]))
cat("Consolidated results (replace those nine files, do not double-count):\n")
print(colSums(combined[counts]))
cat("Files:", length(unique(combined$file)), "test blocks:", nrow(combined), "\n")
write.csv(combined[setdiff(names(combined), "result")],
          file.path(base, "consolidated-unit-results.csv"), row.names = FALSE)
stopifnot(!any(combined$failed > 0 | combined$error), !any(combined$warning > 0))
