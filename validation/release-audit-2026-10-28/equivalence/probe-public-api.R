pkgload::load_all('.', quiet = TRUE)
set.seed(2812)
d <- data.frame(y = rnorm(100L))
str(d)
a <- lpa(d, 'y', n_profiles = 1L, n_starts = 1L, seed = 1L)
b <- lpa(d, 'y', n_profiles = 2L, n_starts = 2L, seed = 1L)
c <- lpa(d, 'y', n_profiles = 2L, model = 'EEI', n_starts = 2L, seed = 1L)
cat('\nDIRECT COLLIDING LABEL\n')
direct <- compare_models(first = a, second = b, n_profiles = c)
print(as.data.frame(direct))
cat('\nFORWARDED COLLIDING LABEL\n')
wrapper <- function(...) compare_models(..., n_profiles = c)
forwarded <- wrapper(first = a, second = b)
print(as.data.frame(forwarded))
print(names(attr(forwarded, 'models')))
stopifnot(nrow(direct) == 3L, nrow(forwarded) == 2L)
cat('\nALL MODEL TABLES\n')
all_tables <- get_results(a, 'all')
print(names(all_tables))
stopifnot(all(vapply(all_tables, is.data.frame, logical(1))))
cat('\nDIAGNOSTIC CONSISTENCY\n')
diagnostic <- diagnostics(a, plots = FALSE)
print(as.data.frame(get_results(diagnostic, 'entropy')))
stopifnot(isTRUE(all.equal(as.data.frame(get_results(diagnostic, 'classification')), as.data.frame(get_results(a, 'classification')))))
cat('\nPOOLED COEFFICIENT/COVARIANCE/INTERVAL ALIGNMENT\n')
d$id <- seq_len(nrow(d))
d2 <- d
d2$y <- d2$y + rnorm(nrow(d2), sd = 0.05)
pooled <- pool_imputations(list(d, d2), vars = 'y', id = 'id', n_profiles = 1L, n_group_classes = 1L, n_starts = 1L)
est <- get_results(pooled, 'estimates')
ci <- confint(pooled, level = pooled$level)
stopifnot(identical(names(coef(pooled)), rownames(vcov(pooled))), isTRUE(all.equal(unname(ci[, 1L]), est$conf_low)), isTRUE(all.equal(unname(ci[, 2L]), est$conf_high)))
print(coef(pooled))
print(ci)

cat('GENERIC FORWARDER\n')
generic_wrapper <- function(...) compare_models(...)
generic_result <- try(generic_wrapper(first = a, second = b, n_profiles = c))
print(generic_result)
