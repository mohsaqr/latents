pkgload::load_all('.', quiet = TRUE)
set.seed(2811)
d <- data.frame(x = rnorm(120L))
d$y <- 2 + 0.7 * d$x + rnorm(120L)
fit <- mixture_regression(y ~ x, d, n_classes = 1L, variance = 'equal', n_starts = 1L, seed = 1L)
print(fit$converged)
print(coef(fit))
print(as.data.frame(get_results(fit, 'classes')))
print(c(expected_sigma = sqrt(fit$params$sigma2)))
stopifnot(fit$converged, is.na(get_results(fit, 'classes')$sigma))
