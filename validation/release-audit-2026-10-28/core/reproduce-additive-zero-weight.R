Sys.setenv(OMP_NUM_THREADS=1,OPENBLAS_NUM_THREADS=1,VECLIB_MAXIMUM_THREADS=1)
library(latents, lib.loc='/private/tmp/latents-release-audit-20261028/lib')
set.seed(271)
d <- data.frame(id=rep(seq_len(30),each=4),x=rep(rnorm(30),each=4)+rnorm(120),w=1)
fit <- function(data) suppressWarnings(multilpa(data,'x','id',family='additive',n_group_classes=2,weights='w',n_starts=2,seed=3))
base <- fit(d)
stopifnot(base$converged, is.finite(base$log_likelihood))
print(c(base_loglik=base$log_likelihood))
result <- lapply(c(1e3,1e4,1e5,999999,1e6),function(magnitude) {
 extra<-data.frame(id=rep(31:32,each=4),x=magnitude+rep(c(-1,1),4),w=0)
 f<-tryCatch(fit(rbind(d,extra)),error=identity)
 data.frame(magnitude,expected_loglik=base$log_likelihood,actual=if(inherits(f,'error')) conditionMessage(f) else format(f$log_likelihood,digits=16),condition=if(inherits(f,'error'))class(f)[1] else 'none')
})
print(do.call(rbind,result),row.names=FALSE)
stopifnot(result[[5]]$actual=='posterior rows must sum to one')
cat('Confirmed defect: excluded finite groups make an otherwise converged model fail.\n')
