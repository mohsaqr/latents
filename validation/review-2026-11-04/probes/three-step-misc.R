cat("=== 4. Row-order invariance of three_step and r3step (group-level, numeric and categorical)\n")
G <- 60; m <- 8; g <- rep(seq_len(G),each=m); gc <- rep(1:2,length.out=G); N <- G*m
tt <- 1L+(runif(N)<c(.25,.75)[gc[g]])
dd <- data.frame(g=paste0("g",g), a=rnorm(N,c(-1.5,1.5)[tt]), b=rnorm(N,c(-1.3,1.3)[tt]), gy=rep(rnorm(G,c(0,2)[gc]),each=m), gz=rep(rnorm(G,c(-.5,.5)[gc]),each=m), gcat=rep(ifelse(runif(G)<c(.3,.7)[gc],"p","q"),each=m))
f1 <- multilpa(dd,c("a","b"),"g",n_profiles=2,n_group_classes=2,n_starts=5,seed=1,tol=1e-10)
o <- sample(N); dds <- dd[o,]
f2 <- multilpa(dds,c("a","b"),"g",n_profiles=2,n_group_classes=2,n_starts=5,seed=1,tol=1e-10)
cmp <- function(a,b,lab) cat(sprintf("%-28s LLdiff %.2e; est: %s | %s\n",lab,f1$log_likelihood-f2$log_likelihood,paste(format(a$estimate,digits=6),collapse=" "),paste(format(b$estimate,digits=6),collapse=" ")))
cmp(three_step(f1,dd,"gy",level="groups"),three_step(f2,dds,"gy",level="groups"),"groups bch")
cmp(three_step(f1,dd,"gy",level="groups",method="ml"),three_step(f2,dds,"gy",level="groups",method="ml"),"groups ml")
cmp(three_step(f1,dd,"gcat",level="groups"),three_step(f2,dds,"gcat",level="groups"),"groups cat")
cmp(r3step(f1,dd,"gz",level="groups"),r3step(f2,dds,"gz",level="groups"),"groups r3step")
