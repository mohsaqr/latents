scan <- function(label, make_y, sep=.8, K=3, n=300) {
  mus <- list(c(-sep,-sep),c(sep,-sep),c(0,sep))[seq_len(K)]
  tr <- sample.int(K,n,TRUE); x <- data.frame(a=rnorm(n,vapply(mus,`[`,0,1)[tr]),b=rnorm(n,vapply(mus,`[`,0,2)[tr]))
  x$y <- make_y(tr,n)
  f <- lpa(x,c("a","b"),n_profiles=K,n_starts=5,seed=1)
  bch <- as.data.frame(three_step(f,x,"y")); ml <- wrap(as.data.frame(three_step(f,x,"y",method="ml")))
  pc <- .multilpa_level_assignments(f,"individuals")
  fit_ml <- wrap(.multilpa_step_ml_fit(pc,x$y,"varying"))
  cat(sprintf("%-20s D-diag %s\n   BCH means %s\n   ML  means %s\n   ML  var   %s  var(y)=%.2f  r_n %s\n",label,
    paste(format(diag(.multilpa_error_matrix(pc)),digits=2),collapse=" "),paste(format(bch$estimate,digits=3),collapse=" "),paste(format(ml$estimate,digits=3),collapse=" "),
    paste(format(ml$variance,digits=3),collapse=" "),var(x$y),paste(format(ml$effective_n,digits=4),collapse=" ")))
}
