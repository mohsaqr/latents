try_lrt <- function(label, ...) {
  r <- tryCatch(withCallingHandlers({
    t <- as.data.frame(compare_models(..., test = "lrt"))
    sprintf("OK LR=%.4f df=%s p=%.4g", t$lr_statistic[2], t$lr_df[2], t$lr_p_value[2])
  }, warning = function(w) { cat("  [warning]", class(w)[1], conditionMessage(w), "\n"); invokeRestart("muffleWarning") }),
  error = function(e) paste("REFUSED", class(e)[1], ":", substr(conditionMessage(e), 1, 150)))
  cat(sprintf("%-46s %s\n", label, r))
}
