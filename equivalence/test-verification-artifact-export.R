test_that("verification tables are written only to an explicitly declared artifact directory", {
  environment <- new.env(parent = globalenv())
  sys.source("helper-equivalence.R", envir = environment)
  withr::local_options(latents.equivalence.output_dir = NULL)
  table <- data.frame(seed = 1:2, original = c(-100, -101), verified = c(-99, -99))
  expect_null(environment$equivalence_write_tables("probe", list(diagnostics = table)))
  output <- tempfile("equivalence-artifacts-")
  withr::local_options(latents.equivalence.output_dir = output)
  environment$equivalence_write_tables("probe", list(diagnostics = table))
  path <- file.path(output, "probe", "diagnostics.csv")
  expect_true(file.exists(path))
  expect_equal(utils::read.csv(path), table, ignore_attr = TRUE)
  environment$equivalence_write_tables("probe", list(other = table))
  expect_true(file.exists(path))
  expect_setequal(list.files(file.path(output, "probe")), c("diagnostics.csv", "other.csv"))
})
